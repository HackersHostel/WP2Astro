/**
 * Where media goes: copied into the repo, into the repo through Git LFS, left on WordPress, or uploaded to object
 * storage (S3, Cloudflare R2, Bunny). Size caps, link rewriting and Git LFS pointers.
 */
class WPTA_Media {

	const MODES = array(
		'repo'      => 'Copy into the repo',
		'lfs'       => 'Copy into the repo with Git LFS',
		'wordpress' => 'Leave on WordPress',
		'cdn'       => 'Upload to storage (S3, R2, Bunny)',
	);

	/** Media goes through Git LFS in lfs mode: everything under the uploads folder. */
	const LFS_ATTRIBUTES = "# Generated by WP2Astro: media is stored with Git LFS.\npublic/wp-content/uploads/** filter=lfs diff=lfs merge=lfs -text\n";

	public static function mode( ?array $s = null ): string {
		$m = ( $s ?? WPTA_Settings::get() )['media_mode'] ?? 'repo';
		return isset( self::MODES[ $m ] ) ? $m : 'repo';
	}

	/**
	 * Largest file copied or uploaded, in bytes. Files over it keep their WordPress URL and are listed in
	 * CONVERSION_REPORT.md. The repo default is lower because GitHub's API needs files base64-encoded in memory.
	 */
	public static function max_bytes( string $mode ): int {
		$bytes = 'repo' === $mode ? 25 * MB_IN_BYTES : 50 * MB_IN_BYTES;

		/**
		 * Filters the largest media file WP2Astro copies into the repo, Git LFS or object storage.
		 *
		 * Uploading a file takes a few times its size in PHP memory. Raise this only with a high memory_limit.
		 *
		 * @since 0.3.0
		 *
		 * @param int    $bytes Limit in bytes. Default 25 MB for 'repo', 50 MB for 'lfs' and 'cdn'.
		 * @param string $mode  'repo', 'lfs' or 'cdn'.
		 */
		return max( 1, (int) apply_filters( 'wpta_max_media_bytes', $bytes, $mode ) );
	}

	/** Root-relative uploads path ("/wp-content/uploads"). */
	public static function rel_base(): string {
		return rtrim( WPTA_Exporter::rel_url( wp_get_upload_dir()['baseurl'] ), '/' );
	}

	/** The WordPress address of the uploads folder. */
	public static function wordpress_base(): string {
		return untrailingslashit( wp_get_upload_dir()['baseurl'] );
	}

	/** Absolute address that replaces the uploads path in content, or '' when media is part of the site. */
	public static function base( string $mode ): string {
		if ( 'wordpress' === $mode ) {
			return self::wordpress_base();
		}
		if ( 'cdn' === $mode ) {
			$url = WPTA_Storage::config()['url'];
			return '' === $url ? '' : $url . self::rel_base();
		}
		return '';
	}

	/**
	 * Point root-relative upload links at $abs ("/wp-content/uploads/a.jpg" → "https://cdn.example.com/wp-content/
	 * uploads/a.jpg") in HTML, srcset lists, Markdown links and frontmatter. Pure (unit-tested).
	 */
	public static function rewrite( string $text, string $rel_base, string $abs ): string {
		if ( '' === $abs || '' === $rel_base ) {
			return $text;
		}
		return (string) preg_replace( '#(?<=["\'(\s,=]|^)' . preg_quote( $rel_base, '#' ) . '/#', rtrim( $abs, '/' ) . '/', $text );
	}

	/** Replace one exact link ($from → $to) where it stands alone, e.g. not inside "a.jpg.webp". Pure. */
	public static function relink( string $text, string $from, string $to ): string {
		return (string) preg_replace( '#(?<=["\'(\s,=]|^)' . preg_quote( $from, '#' ) . '(?=[\s"\')?\#,<]|$)#m', $to, $text );
	}

	/** Git LFS pointer file for a stored object. Pure. */
	public static function lfs_pointer( string $oid, int $size ): string {
		return "version https://git-lfs.github.com/spec/v1\noid sha256:{$oid}\nsize {$size}\n";
	}

	/** One line for CONVERSION_REPORT.md. No timestamps or URLs that change between runs. */
	public static function report_line( string $mode, int $count ): string {
		switch ( $mode ) {
			case 'lfs':
				return 'Media files in Git LFS: ' . $count;
			case 'wordpress':
				return 'Media left on WordPress: ' . $count . ' files (' . self::wordpress_base() . ')';
			case 'cdn':
				return 'Media files in object storage: ' . $count . ' (' . WPTA_Storage::config()['url'] . ')';
		}
		return 'Media files copied: ' . $count;
	}
}
