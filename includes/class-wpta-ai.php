/**
 * The two AI steps. Single-shot prompts, strict validation, deterministic fallback.
 * No tool calling, so small local models (Gemma via Ollama) work as well as big hosted ones.
 */
class WPTA_AI {

	const LAYOUT_SYSTEM = 'You convert WordPress themes into Astro components. Reply with the contents of ONE .astro file and nothing else: no explanation, no Markdown fences.';

	const CLEANUP_SYSTEM = 'You repair Markdown exported from an old WordPress site. Reply with the full corrected Markdown document and nothing else.';

	/* ------------------------------------------------------------- Layout */

	/**
	 * @return array{code:?string, log:string[]}
	 */
	public static function layout( WPTA_LLM $llm, string $home_html, array $site, string $theme_fallback = '' ): array {
		$log    = array();
		$source = self::trim_html( $home_html );
		if ( '' === $source ) {
			$source = $theme_fallback;
			$log[]  = 'Loopback request failed; using theme template files as the layout source.';
		}
		if ( '' === trim( $source ) ) {
			return array( 'code' => null, 'log' => array_merge( $log, array( 'No layout source available; using the default layout.' ) ) );
		}

		$prompt = self::layout_prompt( $source, $site );
		$error  = '';
		for ( $attempt = 1; $attempt <= 2; $attempt++ ) {
			$msg = $prompt;
			if ( $error ) {
				$msg .= "\n\nYour previous answer was rejected: {$error}\nReturn a corrected file.";
			}
			$out = $llm->chat( self::LAYOUT_SYSTEM, $msg );
			if ( is_wp_error( $out ) ) {
				$log[] = 'Layout attempt ' . $attempt . ' failed: ' . $out->get_error_message();
				break; // API errors won't fix themselves on retry.
			}
			$error = self::validate_layout( $out );
			if ( '' === $error ) {
				$log[] = 'Layout generated by ' . $llm->model() . ' (attempt ' . $attempt . ').';
				return array( 'code' => $out, 'log' => $log );
			}
			$log[] = 'Layout attempt ' . $attempt . ' rejected: ' . $error;
		}
		$log[] = 'Using the default layout.';
		return array( 'code' => null, 'log' => $log );
	}

	private static function layout_prompt( string $source, array $site ): string {
		$menu = wp_json_encode( $site['menu'], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE );
		$css  = wp_json_encode( $site['stylesheets'], JSON_UNESCAPED_SLASHES );
		return <<<TXT
Rebuild this WordPress site's page shell (head, header, navigation, footer) as an Astro layout: src/layouts/BaseLayout.astro.

RULES — the file is rejected if any rule is broken:
1. Start with a frontmatter block between two `---` lines.
2. The ONLY import allowed is: import site from '../site.json';
3. Declare props: const { title, description = site.description } = Astro.props;
4. <title> is `title ? \`\${title} – \${site.title}\` : site.title`.
5. In <head>, render every stylesheet: {site.stylesheets.map((href) => <link rel="stylesheet" href={href} />)}
6. Render the navigation from site.menu (items have `label` and `url`), not hard-coded links.
7. Put <slot /> exactly where the page content goes (where the source shows <!-- PAGE CONTENT -->).
8. Keep the theme's element structure, ids and class names so its CSS still applies.
9. Use site.title / site.description instead of hard-coded site name text.
10. No PHP, no <script> tags, no WordPress admin bar, no comments forms, no widgets that need a server.
11. Use `class`, not `className`. Close every tag.
12. Keep theme images (logo, header image) with their /theme/… paths exactly as in the source.

site.json contains: title, description, url, language, menu, stylesheets.
site.menu = {$menu}
site.stylesheets = {$css}

RENDERED HTML OF THE HOMEPAGE (scripts and styles removed):
{$source}
TXT;
	}

	/** Returns '' when valid, otherwise the reason. */
	public static function validate_layout( string $code ): string {
		$code = trim( $code );
		if ( ! preg_match( '/^---\s*\n(.*?)\n---\s*\n(.*)$/s', $code, $m ) ) {
			return 'missing the --- frontmatter block at the top.';
		}
		[ , $front, $tpl ] = $m;
		if ( preg_match_all( '/^\s*import\s+(.+?)\s+from\s+[\'"]([^\'"]+)[\'"]/m', $front, $imports, PREG_SET_ORDER ) ) {
			foreach ( $imports as $imp ) {
				if ( '../site.json' !== $imp[2] ) {
					return "import from '{$imp[2]}' is not allowed.";
				}
			}
		}
		if ( preg_match( '/^\s*import\s+[\'"]/m', $front ) ) {
			return 'side-effect imports are not allowed.';
		}
		if ( false === strpos( $front, '../site.json' ) ) {
			return "missing `import site from '../site.json'`.";
		}
		$checks = array(
			'<slot'            => 'missing <slot />.',
			'site.stylesheets' => 'stylesheets are not rendered from site.stylesheets.',
			'site.menu'        => 'navigation is not rendered from site.menu.',
			'<html'            => 'missing <html> element.',
			'</html>'          => 'missing </html>.',
		);
		foreach ( $checks as $needle => $err ) {
			if ( false === strpos( $code, $needle ) ) {
				return $err;
			}
		}
		if ( preg_match( '/<\?php|className=|<script\b|Astro\.glob|import\.meta\.glob/i', $code, $bad ) ) {
			return "contains forbidden code: {$bad[0]}";
		}
		if ( substr_count( $tpl, '{' ) !== substr_count( $tpl, '}' ) ) {
			return 'unbalanced { } braces in the template.';
		}
		return '';
	}

	/** Keep the page shell, drop noise and the middle (content) of the page. */
	public static function trim_html( string $html, int $limit = 7000 ): string {
		if ( '' === trim( $html ) ) {
			return '';
		}
		$html = WPTA_Exporter::theme_paths( WPTA_Exporter::relative( $html ) );
		$html = preg_replace( '#<(script|style|noscript|svg|template)\b.*?</\1>#is', '', $html );
		$html = preg_replace( '#<!--.*?-->#s', '', $html );
		$html = preg_replace( '#<(link|meta)\b[^>]*>#i', '', $html );
		$html = preg_replace( '/\s(?:style|srcset|sizes|data-[\w-]+|aria-[\w-]+|loading|decoding|fetchpriority)="[^"]*"/i', '', $html );
		$html = preg_replace( '#<div id="wpadminbar".*?</div>\s*</div>#is', '', $html );
		$html = preg_replace( "/\n\s*\n+/", "\n", $html );

		$body_start = stripos( $html, '<body' );
		$body_end   = strripos( $html, '</body>' );
		if ( false === $body_start ) {
			return mb_substr( trim( $html ), 0, $limit );
		}
		$body = substr( $html, $body_start, ( false === $body_end ? strlen( $html ) : $body_end + 7 ) - $body_start );

		// Cut out the content area; keep its opening tag so the model sees the wrapper.
		if ( preg_match( '#<(main|article)\b[^>]*>#i', $body, $open, PREG_OFFSET_CAPTURE ) ) {
			$start = $open[0][1] + strlen( $open[0][0] );
			$tag   = strtolower( $open[1][0] );
			$close = 'main' === $tag ? strripos( $body, '</main>' ) : strripos( $body, '</article>' );
			if ( false !== $close && $close > $start ) {
				$body = substr( $body, 0, $start ) . "\n<!-- PAGE CONTENT -->\n" . substr( $body, $close );
			}
		}
		$head = preg_match( '#<head\b.*?</head>#is', $html, $h ) ? $h[0] : '';
		$out  = trim( $head . "\n" . $body );
		if ( mb_strlen( $out ) > $limit ) {
			$half = (int) ( $limit / 2 );
			$out  = mb_substr( $out, 0, $half ) . "\n<!-- … trimmed … -->\n" . mb_substr( $out, -$half );
		}
		return $out;
	}

	/** Raw theme templates for when the loopback request fails. */
	public static function theme_source( int $limit = 7000 ): string {
		$files = array( 'header.php', 'footer.php', 'parts/header.html', 'parts/footer.html', 'templates/index.html' );
		$out   = '';
		foreach ( $files as $f ) {
			$path = locate_template( $f ) ?: ( is_readable( get_stylesheet_directory() . '/' . $f ) ? get_stylesheet_directory() . '/' . $f : '' );
			if ( $path ) {
				$out .= "\n<!-- FILE: {$f} -->\n" . file_get_contents( $path );
			}
		}
		return mb_substr( trim( $out ), 0, $limit );
	}

	/* ------------------------------------------------------------ Cleanup */

	/**
	 * @return string|WP_Error New Markdown document (frontmatter untouched).
	 */
	public static function cleanup( WPTA_LLM $llm, string $doc, array $shortcodes ) {
		if ( ! preg_match( '/^(---\n.*?\n---\n\n?)(.*)$/s', $doc, $m ) ) {
			return new WP_Error( 'wpta_doc', 'Could not split frontmatter.' );
		}
		[ , $front, $body ] = $m;
		if ( mb_strlen( $body ) > 30000 ) {
			return new WP_Error( 'wpta_long', 'Post is too long for AI cleanup.' );
		}

		$names  = implode( ', ', array_map( fn( $s ) => '[' . $s . ']', $shortcodes ) );
		$prompt = <<<TXT
This Markdown came from a WordPress post. The plugins behind these shortcodes are gone, so they show up as raw text: {$names}

Replace each leftover shortcode with the closest plain Markdown or HTML equivalent:
- [caption]…[/caption] → the image followed by the caption in italics
- [gallery …] → remove it (the images are not available)
- [embed]URL[/embed], [youtube …], [vimeo …] → a plain link to the URL
- buttons → a normal Markdown link
- layout wrappers (columns, rows, boxes, tabs, accordions) → remove the tags, keep the text inside
- anything that produced no visible content → remove it

Do NOT change, rephrase, translate or summarize any other text. Keep all links, images and headings as they are.

DOCUMENT:
{$body}
TXT;

		$out = $llm->chat( self::CLEANUP_SYSTEM, $prompt, false );
		if ( is_wp_error( $out ) ) {
			return $out;
		}

		// Guard against the model rewriting the post: compare text length without shortcodes.
		$strip = fn( $t ) => mb_strlen( preg_replace( '/\[[^\]]*\]|\s+/', '', $t ) );
		$a     = $strip( $body );
		$b     = $strip( $out );
		if ( $a > 200 && ( $b < $a * 0.7 || $b > $a * 1.3 ) ) {
			return new WP_Error( 'wpta_guard', sprintf( 'Rejected: model changed the text length too much (%d → %d chars).', $a, $b ) );
		}
		return $front . trim( $out ) . "\n";
	}
}
